# IN - caso o objeto esteja presente na sequência, o operador in retorna True, caso contrário, retorna False. 
# O operador not in é o inverso do operador in, ou seja, ele retorna True se o objeto não estiver presente na sequência e False se estiver presente.

# NOT IN - caso o objeto não esteja presente na sequência, o operador not in retorna True, caso contrário, retorna False.
# O operador in é o inverso do operador not in, ou seja, ele retorna True se o objeto estiver presente na sequência e False se não estiver presente.

frutas = ["limão", "uva", "laranja"]
curso = "Bootcamp Afya Automação de Dados"

# exemplos práticos de operadores de associação in e not in
print("laranja" in frutas)
print("limão" not in frutas)
print("Afya" in curso)